DROP TABLE IF EXISTS Person;
DROP TABLE IF EXISTS Article;
DROP TABLE IF EXISTS PersonComment;
DROP TABLE IF EXISTS PersonLike;

CREATE TABLE Person (
	id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(100) NOT NULL,
	surname VARCHAR(100) NOT NULL,
	email VARCHAR UNIQUE NOT NULL,
	password_hash VARCHAR NOT NULL
);

CREATE TABLE Article (
	id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	title VARCHAR(255),
	content VARCHAR,
	image_url VARCHAR,
	created_at TIMESTAMP
);

CREATE TABLE PersonComment (
	id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	content VARCHAR(1000),
	created_at TIMESTAMP,
	person_id INT,
	article_id INT,
	FOREIGN KEY (person_id) REFERENCES Person(id) ON UPDATE CASCADE ON DELETE CASCADE,
	FOREIGN KEY (article_id) REFERENCES Article(id) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE PersonLike (
	id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	person_id INT,
	article_id INT,
	FOREIGN KEY (person_id) REFERENCES Person(id) ON UPDATE CASCADE ON DELETE CASCADE,
	FOREIGN KEY (article_id) REFERENCES Article(id) ON UPDATE CASCADE ON DELETE CASCADE,
	UNIQUE (person_id, article_id)
);
